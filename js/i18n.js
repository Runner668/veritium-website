const storageKey = 'veritium-language';
let initialized = false;

function setLanguage(language) {
    const activeLanguage = translations[language] ? language : 'de';
    const dictionary = translations[activeLanguage];

    document.documentElement.lang = activeLanguage;
    document.body.dataset.language = activeLanguage;

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const value = dictionary[element.dataset.i18n];
        if (typeof value !== 'undefined') element.textContent = value;
    });

    document.querySelectorAll('[data-i18n-html]').forEach((element) => {
        const value = dictionary[element.dataset.i18nHtml];
        if (typeof value !== 'undefined') element.innerHTML = value;
    });

    document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
        const [attribute, key] = element.dataset.i18nAttr.split(':');
        const value = dictionary[key];
        if (attribute && typeof value !== 'undefined') element.setAttribute(attribute, value);
    });

    document.querySelectorAll('[data-language-panel]').forEach((panel) => {
        panel.hidden = panel.dataset.languagePanel !== activeLanguage;
    });

    document.querySelectorAll('[data-lang]').forEach((button) => {
        const isActive = button.dataset.lang === activeLanguage;
        button.classList.toggle('is-active', isActive);
        button.setAttribute('aria-pressed', String(isActive));
    });

    try {
        window.localStorage.setItem(storageKey, activeLanguage);
    } catch (error) {
        // Storage can be disabled in privacy-focused browser contexts.
    }

    window.dispatchEvent(new CustomEvent('veritium:languagechange', { detail: activeLanguage }));
}

export function initI18n() {
    if (initialized) return;
    initialized = true;

    let preferredLanguage = 'de';
    try {
        const savedLanguage = window.localStorage.getItem(storageKey);
        if (savedLanguage && translations[savedLanguage]) preferredLanguage = savedLanguage;
    } catch (error) {
        // Ignore storage access errors and use the German default.
    }

    document.querySelectorAll('[data-lang]').forEach((button) => {
        button.addEventListener('click', () => setLanguage(button.dataset.lang));
    });

    setLanguage(preferredLanguage);
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n, { once: true });
} else {
    initI18n();
}
